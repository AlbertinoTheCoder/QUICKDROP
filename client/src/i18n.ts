export function translate(language: Language, message: string, values: Record<string, string | number> = {}): string {
  if (language === 'it' && message.startsWith('Invalid transfer: ')) return 'Trasferimento non valido: ' + translate(language, message.slice(18));
  const text = language === 'it' ? italian[message] ?? message : message;
  return text.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder));
}
